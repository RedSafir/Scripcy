"""Devil's Advocate module: adversarial peer review, scope guard, and recency verification."""

from __future__ import annotations

from datetime import datetime
import json
import re
from typing import Any
from pydantic import BaseModel, Field

from scripcy.core.engine import LLMEngine, estimate_tokens


def _clean_json_payload(raw: str) -> str:
    clean = raw.strip()
    if clean.startswith("```"):
        clean = re.sub(r"^```[a-zA-Z]*\r?\n", "", clean)
        clean = re.sub(r"\r?\n```$", "", clean)
    return clean.strip()


class CritiqueReport(BaseModel):
    """Evaluation report generated by the Devil's Advocate review."""

    score: int = Field(ge=1, le=10, description="Overall robustness score (1 to 10).")
    passed: bool = Field(description="True if synthesis meets rigorous scientific standard (score >= 7 and both audit layers pass).")
    contract_conformance: bool = Field(
        default=True,
        description="Layer 1: True if Definition of Done items and format/word budget within tolerance are satisfied.",
    )
    conformance_details: list[str] = Field(
        default_factory=list,
        description="Detailed assessment of DoD checklist and format/word tolerance.",
    )
    epistemic_rigor: bool = Field(
        default=True,
        description="Layer 2: True if citations are valid and claims are grounded in vault evidence without hallucination.",
    )
    epistemic_details: list[str] = Field(
        default_factory=list,
        description="Detailed assessment of factual grounding and citation veracity.",
    )
    weaknesses: list[str] = Field(default_factory=list, description="Identified logical or empirical vulnerabilities.")
    counter_arguments: list[str] = Field(default_factory=list, description="Substantive counter-perspectives or caveats.")
    recency_alert: str | None = Field(default=None, description="Warning if references are outdated.")
    needs_citation_mapping: bool = Field(default=False, description="True if new/recent references should be scouted.")
    recommended_topics: list[str] = Field(default_factory=list, description="Key missing topics or questions to explore.")
    directed_search_queries: list[str] = Field(default_factory=list, description="Targeted academic search queries to fill evidence gaps.")
    directed_web_queries: list[str] = Field(default_factory=list, description="Targeted official web queries to fill data/statistical gaps.")
    critique_summary: str = Field(default="", description="Concise reviewer assessment.")
    input_tokens: int = Field(default=0, description="Estimated input tokens consumed during critique.")
    output_tokens: int = Field(default=0, description="Estimated output tokens consumed during critique.")


class PlanAuditReview(BaseModel):
    """Pre-flight evaluation of proposed execution plan by Devil's Advocate."""

    prune_ids: list[str] = Field(
        default_factory=list,
        description="Subcontract IDs challenged and deemed unsubstantial, redundant, or out-of-scope.",
    )
    prune_reasons: dict[str, str] = Field(
        default_factory=dict,
        description="Substantive reasoning for why each subcontract should be pruned.",
    )
    additions: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Missing substantive dimensions or micro-tasks proposed for addition.",
    )
    summary: str = Field(default="", description="Concise assessment of the plan.")
    input_tokens: int = Field(default=0, description="Tokens used for plan audit.")
    output_tokens: int = Field(default=0, description="Tokens used for plan audit.")


class EvidenceAuditReview(BaseModel):
    """Post-execution evaluation by Devil's Advocate assessing whether worker findings satisfy contract."""

    all_satisfied: bool = Field(default=True, description="True if extracted facts satisfy contract objectives without crucial gaps.")
    detected_gaps: list[str] = Field(default_factory=list, description="Substantive data gaps, missing parameters, or unfulfilled contract dos.")
    suggested_expansion_queries: list[str] = Field(default_factory=list, description="Targeted queries recommended to fill the detected gaps.")
    summary: str = Field(default="", description="Concise assessment of evidence completeness.")
    input_tokens: int = Field(default=0, description="Tokens used for evidence audit.")
    output_tokens: int = Field(default=0, description="Tokens used for evidence audit.")


class DevilsAdvocate:
    """Adversarial critic and scope guard testing contract conformance, evidence recency, and factual rigor."""

    def __init__(self, engine: LLMEngine | None = None, recency_threshold_years: int = 6) -> None:
        self.engine = engine
        self.recency_threshold_years = recency_threshold_years
        self.current_year = datetime.now().year

    def extract_citation_years(self, text: str) -> list[int]:
        """Extract publication years cited in the text."""
        matches = re.findall(r"(?:19\d{2}|20\d{2})", text)
        return [int(y) for y in matches if 1950 <= int(y) <= self.current_year]

    def check_recency(self, citation_years: list[int]) -> tuple[bool, str | None]:
        """Check if cited references are outdated relative to current year."""
        if not citation_years:
            return False, "Tidak ditemukan sitasi tahun publikasi eksplisit dalam jawaban."

        max_year = max(citation_years)
        cutoff_year = self.current_year - self.recency_threshold_years

        if max_year < cutoff_year:
            return True, f"Referensi terbaru yang dikutip berasal dari tahun {max_year} (lebih dari {self.recency_threshold_years} tahun lalu). Diperlukan literatur komplementer terbaru."

        return False, None

    def audit_fact_ledger(
        self,
        query: str,
        contract: Any,
        artifacts: list[Any],
        valid_stems: set[str] | None = None,
    ) -> dict[str, Any]:
        """Audit extracted subagent artifacts before final assembly, filtering out-of-scope drift and ungrounded stems."""
        kept_facts: list[Any] = []
        dropped_count = 0
        missing_notes: list[str] = []
        in_tok = 0
        out_tok = 0

        forbidden_terms = [
            f.lower()
            for f in (list(getattr(contract, "out_of_scope", [])) + list(getattr(contract, "forbidden_drift_topics", [])))
            if len(f) > 4
        ]
        seen_text: set[str] = set()

        for art in artifacts:
            in_tok += getattr(art, "input_tokens", 0)
            out_tok += getattr(art, "output_tokens", 0)
            for m in getattr(art, "missing_requirements", []):
                if m not in missing_notes:
                    missing_notes.append(m)

            for fact in getattr(art, "extracted_facts", []):
                claim_txt = getattr(fact, "claim_or_metric", "").strip()
                stem = getattr(fact, "citation_stem", "").strip()
                if not claim_txt:
                    continue
                if valid_stems and stem and stem not in valid_stems:
                    dropped_count += 1
                    continue
                c_low = claim_txt.lower()
                if any(ft in c_low for ft in forbidden_terms):
                    dropped_count += 1
                    continue
                norm = c_low[:70]
                if norm in seen_text:
                    continue
                seen_text.add(norm)
                kept_facts.append(fact)

        if getattr(contract, "archetype", "") == "DATA_FACTUAL":
            kept_facts.sort(key=lambda f: (1 if getattr(f, "is_quantitative", False) else 0, getattr(f, "year", "") or ""), reverse=True)

        return {
            "verified_facts": kept_facts,
            "dropped_count": dropped_count,
            "missing_notes": missing_notes,
            "subagent_input_tokens": in_tok,
            "subagent_output_tokens": out_tok,
        }

    def audit_execution_plan(
        self,
        query: str,
        contract: Any,
        subcontracts: list[Any],
    ) -> PlanAuditReview:
        """Pre-flight audit: challenge unsubstantial/redundant subcontracts and propose missing substantive needs."""
        if not subcontracts:
            return PlanAuditReview(summary="Rencana kosong; tidak ada subkontrak untuk diaudit.")

        prune_ids: list[str] = []
        prune_reasons: dict[str, str] = {}
        additions: list[dict[str, Any]] = []

        forbidden = [p.lower() for p in (list(getattr(contract, "out_of_scope", [])) + list(getattr(contract, "forbidden_drift_topics", []))) if p]

        # 1. Challenge & prune unsubstantial or out-of-scope subcontracts
        seen_objectives: set[tuple[str, ...]] = set()
        for sc in subcontracts:
            obj_lower = sc.objective.lower()

            # Check if clearly out-of-scope
            is_forbidden = any(f in obj_lower for f in forbidden if len(f) > 3)
            if is_forbidden:
                prune_ids.append(sc.id)
                prune_reasons[sc.id] = "Subkontrak melanggar batas out-of-scope kontrak."
                continue

            # Check redundancy (near identical objective)
            key_words = tuple(sorted(set(re.findall(r"\b\w{4,}\b", obj_lower)) - {"ekstrak", "bukti", "untuk", "data", "fakta"}))
            if key_words in seen_objectives and len(key_words) >= 2:
                prune_ids.append(sc.id)
                prune_reasons[sc.id] = "Subkontrak redundant/tumpang tindih dengan subkontrak lain."
                continue
            if key_words:
                seen_objectives.add(key_words)

        # 2. Identify missing substantive dimensions
        # If user explicitly asked for data/angka/luas but no subcontract has quantitative objective
        q_lower = query.lower()
        has_quant_req = any(w in q_lower for w in ("berapa", "luas", "jumlah", "angka", "data", "statistik", "hektare", "ha", "tren"))
        has_quant_sub = any("angka" in sc.objective.lower() or "metrik" in sc.objective.lower() or "kuantitatif" in sc.objective.lower() for sc in subcontracts if sc.id not in prune_ids)
        if has_quant_req and not has_quant_sub:
            additions.append({
                "role": "WebScout" if hasattr(contract, "archetype") and contract.archetype == "DATA_FACTUAL" else "VaultExtractor",
                "objective": f"Ekstrak angka, metrik numerik, dan tren kuantitatif resmi terkait: '{query}'.",
                "target_channel": "web_resmi" if hasattr(contract, "archetype") and contract.archetype == "DATA_FACTUAL" else "vault_lokal",
                "dos": ["Ambil angka numerik, unit, dan tahun rilis resmi."],
                "donts": ["Jangan berspekulasi atau mengambil opini kualitatif."],
                "search_queries": [f"{query} data statistik resmi"],
            })

        summary = f"Plan audit selesai: {len(prune_ids)} dipangkas (tidak substansial/redundant), {len(additions)} usulan penambahan."
        return PlanAuditReview(
            prune_ids=prune_ids,
            prune_reasons=prune_reasons,
            additions=additions,
            summary=summary,
        )

    def audit_worker_evidence(
        self,
        query: str,
        contract: Any,
        subcontracts: list[Any],
        artifacts: list[Any],
    ) -> EvidenceAuditReview:
        """Post-scout audit: challenge extracted worker facts against Small Contract objectives and identify missing data."""
        detected_gaps: list[str] = []
        suggested_queries: list[str] = []

        all_facts = [f for art in artifacts for f in getattr(art, "extracted_facts", [])]
        combined_claims = " ".join(f.claim_or_metric for f in all_facts).lower()
        years_found = [int(f.year) for f in all_facts if getattr(f, "year", None) and str(f.year).isdigit()]

        lower_q = query.lower()
        clean_words = [
            w for w in re.findall(r"\b\w{4,}\b", lower_q)
            if w not in {
                "yang", "untuk", "dengan", "dalam", "pada", "oleh", "dari", "tentang",
                "bagaimana", "apakah", "berapa", "carikan", "tolong", "buatkan", "data",
                "tahun", "terakhir",
            }
        ]
        base_topic = " ".join(clean_words[:5]) if clean_words else query[:50]

        # 1. Check whether worker reported limitations or missing requirements in worker_notes
        for art in artifacts:
            w_notes = getattr(art, "worker_notes", "") or ""
            missing_reqs = getattr(art, "missing_requirements", []) or []
            if getattr(art, "status", "") in ("partial", "no_data"):
                if w_notes and "tidak ada" in w_notes.lower():
                    detected_gaps.append(f"Worker [{art.role}] melaporkan kendala: {w_notes}")
                for m in missing_reqs:
                    if m not in detected_gaps:
                        detected_gaps.append(f"Worker [{art.role}] missing requirement: {m}")

        # 2. Check temporal completeness for recent years queries (e.g. 5 tahun terakhir)
        asks_recent = any(
            p in lower_q
            for p in ("5 tahun terakhir", "lima tahun terakhir", "terbaru", "mutakhir", "2023", "2024", "2025")
        )
        if asks_recent:
            max_year = max(years_found) if years_found else 0
            if max_year < self.current_year - 2:
                gap_msg = (
                    f"Pertanyaan meminta data terbaru (5 tahun terakhir), namun temuan worker "
                    f"hanya mencakup hingga tahun {max_year or 'lama'}."
                )
                detected_gaps.append(gap_msg)
                suggested_queries.append(f"{base_topic} data resmi statistik {self.current_year - 2} {self.current_year}")

        # 3. Check quantitative requirements on DATA_FACTUAL queries
        archetype = getattr(contract, "archetype", "")
        if archetype == "DATA_FACTUAL" or any(w in lower_q for w in ("berapa", "luas", "jumlah", "angka", "statistik")):
            has_quant = any(getattr(f, "is_quantitative", False) for f in all_facts)
            if not has_quant and not all_facts:
                gap_msg = "Belum ditemukan angka atau metrik statistik resmi yang memadai dari pencarian awal."
                detected_gaps.append(gap_msg)
                suggested_queries.append(f"{base_topic} data statistik resmi kementerian lembaga bps")

        all_satisfied = len(detected_gaps) == 0
        summary = (
            "Temuan worker telah memenuhi kontrak."
            if all_satisfied
            else f"Devil's Advocate mendeteksi {len(detected_gaps)} gap pada temuan worker."
        )

        return EvidenceAuditReview(
            all_satisfied=all_satisfied,
            detected_gaps=detected_gaps,
            suggested_expansion_queries=suggested_queries,
            summary=summary,
        )

    def critique_heuristic(
        self,
        query: str,
        answer: str,
        intent: str | None = None,
        contract: Any | None = None,
        fact_check_verdict: Any | None = None,
    ) -> CritiqueReport:
        """Rule-based critique testing contract conformance, scope boundaries, and epistemic rigor."""
        years = self.extract_citation_years(answer)
        is_outdated, recency_msg = self.check_recency(years)

        weaknesses: list[str] = []
        counter_args: list[str] = []
        recommended_topics: list[str] = []
        conformance_details: list[str] = []
        epistemic_details: list[str] = []
        score = 8
        contract_conformance = True
        epistemic_rigor = True

        words = len(answer.split())
        archetype = getattr(contract, "archetype", "") if contract else ""
        allow_counter = getattr(contract, "allow_counter_arguments", True) if contract else True

        if contract:
            eff_min = getattr(contract, "effective_min_words", int(getattr(contract, "min_words", 300) * 0.85))
            eff_max = getattr(contract, "effective_max_words", int(getattr(contract, "max_words", 750) * 1.15))
            is_strict_length = getattr(contract, "min_words", 0) >= 300 or getattr(contract, "is_modular_section_needed", False)
            is_unlimited = getattr(contract, "unlimited_tokens", True)

            if is_strict_length and words < eff_min:
                contract_conformance = False
                msg = f"Panjang draf ({words} kata) berada di bawah batas minimum toleransi ({eff_min} kata dari target {getattr(contract, 'min_words', 300)}). Uraikan lebih mendalam."
                conformance_details.append(msg)
                weaknesses.append(msg)
                score -= 2
            elif not is_unlimited and words > eff_max:
                msg = f"Panjang draf ({words} kata) melebihi batas maksimum toleransi ({eff_max} kata dari batas {getattr(contract, 'max_words', 750)}). Pangkas bagian yang keluar dari substansi pertanyaan."
                conformance_details.append(msg)
                weaknesses.append(msg)
                score -= 1
            else:
                conformance_details.append(f"Panjang draf ({words} kata) memenuhi standar elaborasi komprehensif.")

            dods = getattr(contract, "definition_of_done", [])
            for dod in dods:
                conformance_details.append(f"DoD Checklist: '{dod}' terpenuhi.")
        else:
            conformance_details.append("Format umum akademis terpenuhi.")

        if fact_check_verdict:
            grounding_score = getattr(fact_check_verdict, "grounding_score", None)
            if grounding_score is None and isinstance(fact_check_verdict, dict):
                grounding_score = fact_check_verdict.get("grounding_score")

            hallucination_warning = getattr(fact_check_verdict, "hallucination_warning", None)
            if hallucination_warning is None and isinstance(fact_check_verdict, dict):
                hallucination_warning = fact_check_verdict.get("hallucination_warning")

            unsupported_claims = getattr(fact_check_verdict, "unsupported_claims", 0)
            supported_claims = getattr(fact_check_verdict, "supported_claims", 0)

            if grounding_score is not None:
                if grounding_score < 0.70:
                    epistemic_rigor = False
                    msg = f"Skor grounding ({grounding_score:.2f}) di bawah batas rigor ilmiah (0.70)."
                    epistemic_details.append(msg)
                    weaknesses.append(msg)
                    score = min(score, 6)
                else:
                    epistemic_details.append(f"Skor grounding memadai ({grounding_score:.2f} >= 0.70).")

            if hallucination_warning:
                epistemic_rigor = False
                msg = f"Terdeteksi potensi halusinasi: {hallucination_warning}"
                epistemic_details.append(msg)
                weaknesses.append(msg)
                score = min(score, 5)

            if unsupported_claims > 0 and supported_claims == 0:
                epistemic_rigor = False
                msg = "Seluruh klaim substantif tidak memiliki rujukan bukti empiris vault."
                epistemic_details.append(msg)
                score = min(score, 4)
        else:
            paragraphs = [p for p in answer.split("\n\n") if len(p.strip().split()) > 15]
            cited_paragraphs = [p for p in paragraphs if "[" in p and "]" in p]
            is_concise_contract = contract and getattr(contract, "max_words", 1000) <= 650
            min_density = 0.25 if is_concise_contract else 0.40
            if paragraphs and (len(cited_paragraphs) / len(paragraphs)) < min_density:
                weaknesses.append("Sebagian paragraf substantif tidak memiliki rujukan sitasi langsung.")
                if allow_counter:
                    counter_args.append("Klaim tanpa sitasi dapat diperdebatkan validitas empirisnya.")
                epistemic_details.append("Kepadatan sitasi empiris di bawah batas minimum.")
                score -= 2
            else:
                epistemic_details.append("Kepadatan sitasi empiris memadai.")

        if is_outdated and recency_msg:
            weaknesses.append(recency_msg)
            score -= 2

        # Anti-Slop & High-Density Audit
        from scripcy.core.polisher import AcademicPolisher
        slop_density = AcademicPolisher.calculate_slop_density(answer)
        if slop_density > 2.5:
            weaknesses.append(f"Kepadatan klise AI (Slop Density: {slop_density}%) melebihi ambang batas toleransi.")
            score = min(score, 6)

        has_throat_clearing = bool(re.search(r"^(?:tentu\s+saja|tentu|baiklah|berikut\s+adalah|sure|certainly|here\s+is)\b", answer.strip(), re.IGNORECASE))
        if has_throat_clearing:
            weaknesses.append("Terdeteksi basa-basi pembuka (throat-clearing). Respons wajib langsung ke inti temuan ilmiah.")
            score = min(score, 6)

        # Require counter-arguments only when contract permits dialectical debate or when no restrictive contract is set.
        if contract is None or (allow_counter and archetype != "DATA_FACTUAL"):
            nuance_keywords = [
                "namun", "tetapi", "meskipun", "kendala", "tantangan", "limitasi",
                "kontra", "sanggahan", "tegangan", "kritik", "kelemahan", "however", "although", "limitation",
            ]
            has_nuance = any(k in answer.lower() for k in nuance_keywords)
            if not has_nuance:
                weaknesses.append("Argumen cenderung satu arah (belum menyajikan limitasi atau kondisi batas).")
                counter_args.append("Pertimbangkan faktor pembatas, trade-off, atau skenario di mana argumen ini tidak berlaku.")
                score -= 1

        words_q = [w for w in re.split(r"[^\w-]", query.lower()) if len(w) > 3]
        directed_queries: list[str] = []
        directed_web_queries: list[str] = []
        if words_q:
            base_kw = " ".join(words_q[:5])
            recommended_topics.append(f"{base_kw} recent advances limitations")
            directed_queries.append(f"{base_kw} policy community management")
            directed_queries.append(f"{base_kw} empirical evaluation challenges")
            directed_web_queries.append(f"{base_kw} data resmi statistik")
            directed_web_queries.append(f"{base_kw} laporan tahunan portal pemerintah")
        else:
            directed_queries.append(f"{query} review evidence")
            directed_web_queries.append(f"{query} data statistik resmi")

        score = max(1, min(10, score))
        needs_more_scout = score < 7 or is_outdated or not epistemic_rigor
        passed = score >= 7 and contract_conformance and epistemic_rigor and not is_outdated

        summary = "Argumen memenuhi standar ilmiah dan lolos audit ganda." if passed else "Argumen memerlukan perbaikan bukti empiris atau pemenuhan kontrak."
        if is_outdated:
            summary += " Ditemukan indikasi referensi usang."

        return CritiqueReport(
            score=score,
            passed=passed,
            contract_conformance=contract_conformance,
            conformance_details=conformance_details,
            epistemic_rigor=epistemic_rigor,
            epistemic_details=epistemic_details,
            weaknesses=weaknesses,
            counter_arguments=counter_args,
            recency_alert=recency_msg,
            needs_citation_mapping=needs_more_scout,
            recommended_topics=recommended_topics,
            directed_search_queries=directed_queries,
            directed_web_queries=directed_web_queries,
            critique_summary=summary,
        )

    def critique(
        self,
        query: str,
        answer: str,
        intent: str | None = None,
        contract: Any | None = None,
        fact_check_verdict: Any | None = None,
    ) -> CritiqueReport:
        """Execute adversarial critique and scope guard using LLM if available, falling back to heuristics."""
        heuristic = self.critique_heuristic(
            query,
            answer,
            intent=intent,
            contract=contract,
            fact_check_verdict=fact_check_verdict,
        )
        if not self.engine:
            return heuristic

        try:
            model_name = self.engine.config.default_model
            api_key = self.engine.config.get_api_key_for_model(model_name)
            if not api_key or api_key.startswith("mock") or getattr(self.engine, "_acompletion_fn", None) is not None:
                return heuristic

            archetype = getattr(contract, "archetype", "FOCUSED_QA") if contract else "FOCUSED_QA"
            allow_counter = getattr(contract, "allow_counter_arguments", False) if contract else True
            allow_honest_gap = getattr(contract, "allow_honest_gap", True) if contract else True

            contract_note = ""
            if contract:
                p_goal = getattr(contract, "primary_goal", "")
                in_s = ", ".join(getattr(contract, "in_scope", []))
                out_s = ", ".join(getattr(contract, "out_of_scope", []))
                fmt_r = getattr(contract, "format_requirements", "")
                min_w = getattr(contract, "min_words", 300)
                max_w = getattr(contract, "max_words", 750)
                dods = "\n".join(f"  * {d}" for d in getattr(contract, "definition_of_done", []))

                scope_mode_rule = (
                    "2. LENS 2 (SCOPE GUARD - NO EXPANSION): This is a direct data/factual or focused query. "
                    "DO NOT demand counter-arguments, bureaucratic/policy debates, or literature-review sub-chapters. "
                    "Set counter_arguments to [] (empty list). Penalize the answer if it drifts into textbook theory.\n"
                    if not allow_counter
                    else "2. LENS 2 (DIALECTICAL RIGOR): Check whether key counter-arguments, trade-offs, or limitations within scope are addressed.\n"
                )
                honest_gap_rule = (
                    "3. HONEST GAP POLICY: If the vault documents only cover specific regions or years and the answer honestly states that limitation while citing available figures, DO NOT penalize it or force speculative padding.\n"
                    if allow_honest_gap
                    else ""
                )

                budget_note = "UNLIMITED / BEBAS (Prioritaskan elaborasi mendalam dan ketuntasan analisis)" if getattr(contract, "unlimited_tokens", True) else f"~{min_w}-{max_w} words"
                contract_note = (
                    f"\nDYNAMIC TASK CONTRACT & SCOPE GUARD (Archetype: {archetype}):\n"
                    f"- Primary Goal: {p_goal}\n"
                    f"- In-Scope Topics: {in_s}\n"
                    f"- Out-of-Scope (FORBIDDEN DRIFT): {out_s}\n"
                    f"- Target Format & Word Budget: {fmt_r} ({budget_note})\n"
                    f"- Definition of Done (DoD) Checklist:\n{dods}\n\n"
                    "EVALUATION INSTRUCTIONS:\n"
                    "1. LENS 1 (CONTRACT & SUBSTANCE): Verify whether the answer directly answers the user question without drifting into unrequested chapters.\n"
                    + scope_mode_rule
                    + honest_gap_rule
                )
            elif intent and ("argument" in str(intent).lower()):
                contract_note = (
                    "\nNOTE: The user specifically requested an ARGUMENT EXPLORATION / DIALECTICAL MATRIX "
                    "(thesis, pro arguments, contra arguments, and gaps), NOT a monolithic multi-chapter review. "
                    "Grade on dialectical balance, evidentiary backing, and clarity. DO NOT penalize for conciseness.\n"
                )

            system_prompt = (
                "You are an academic Scope & Rigor Auditor.\n"
                "Evaluate whether the proposed answer stays strictly on substance and fulfills the Task Contract.\n"
                + contract_note +
                "Provide structured evaluation in JSON:\n"
                "- score: integer from 1 to 10\n"
                "- weaknesses: list of 1-2 concise issues (focus on missing core data or scope drift; do NOT ask to expand into tangential topics)\n"
                "- counter_arguments: list of 0-2 counter-perspectives (MUST be [] if allow_counter_arguments is False)\n"
                "- recommended_topics: list of 1-2 search queries for complementary literature\n"
                "- directed_search_queries: list of 1-2 specific academic search queries to fill empirical gaps\n"
                "- directed_web_queries: list of 1-2 search queries targeting official government or institutional data portals\n"
                "- critique_summary: 1-sentence verdict"
            )

            import litellm
            litellm.suppress_debug_info = True
            litellm.set_verbose = False
            litellm.drop_params = True

            effective_model = model_name
            api_base = None
            if model_name.startswith("9router/"):
                submodel = model_name.split("/", 1)[1]
                effective_model = f"openai/{submodel}"
                api_base = "http://localhost:20128/v1"

            kwargs: dict[str, Any] = {
                "model": effective_model,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": f"RESEARCH QUESTION: {query}\n\nPROPOSED ANSWER:\n{answer[:6000]}"},
                ],
                "api_key": api_key,
                "temperature": 0.2,
                "max_tokens": 280,
                "response_format": {"type": "json_object"},
                "timeout": 15,
            }
            if api_base:
                kwargs["api_base"] = api_base

            resp = litellm.completion(**kwargs)
            content = resp.choices[0].message.content or "{}"
            data = json.loads(_clean_json_payload(content))

            score = int(data.get("score", heuristic.score))
            score = max(1, min(10, score))
            ai_weaknesses = data.get("weaknesses", heuristic.weaknesses)
            ai_counter = [] if not allow_counter else data.get("counter_arguments", heuristic.counter_arguments)
            ai_topics = data.get("recommended_topics", heuristic.recommended_topics)
            ai_directed = data.get("directed_search_queries", heuristic.directed_search_queries or ai_topics)
            ai_directed_web = data.get("directed_web_queries", getattr(heuristic, "directed_web_queries", []))
            ai_summary = data.get("critique_summary", heuristic.critique_summary)

            if heuristic.recency_alert and heuristic.recency_alert not in ai_weaknesses:
                ai_weaknesses.append(heuristic.recency_alert)

            contract_conformance = heuristic.contract_conformance
            conformance_details = list(heuristic.conformance_details)
            epistemic_rigor = heuristic.epistemic_rigor
            epistemic_details = list(heuristic.epistemic_details)

            if fact_check_verdict:
                grounding_score = getattr(fact_check_verdict, "grounding_score", None)
                hallucination_warning = getattr(fact_check_verdict, "hallucination_warning", None)
                if grounding_score is not None and grounding_score < 0.70:
                    epistemic_rigor = False
                    score = min(score, 6)
                if hallucination_warning:
                    epistemic_rigor = False
                    score = min(score, 5)

            if contract:
                words = len(answer.split())
                eff_min = getattr(contract, "effective_min_words", int(getattr(contract, "min_words", 300) * 0.85))
                if words < eff_min and getattr(contract, "min_words", 0) >= 300:
                    contract_conformance = False
                    score = min(score, 6)

            needs_scout = score < 7 or heuristic.needs_citation_mapping or not epistemic_rigor
            passed = score >= 7 and contract_conformance and epistemic_rigor and not heuristic.recency_alert

            c_in = estimate_tokens(query) + estimate_tokens(answer[:6000]) + 150
            c_out = estimate_tokens(content)

            return CritiqueReport(
                score=score,
                passed=passed,
                contract_conformance=contract_conformance,
                conformance_details=conformance_details,
                epistemic_rigor=epistemic_rigor,
                epistemic_details=epistemic_details,
                weaknesses=ai_weaknesses,
                counter_arguments=ai_counter,
                recency_alert=heuristic.recency_alert,
                needs_citation_mapping=needs_scout,
                recommended_topics=ai_topics,
                directed_search_queries=ai_directed if isinstance(ai_directed, list) else heuristic.directed_search_queries,
                directed_web_queries=ai_directed_web if isinstance(ai_directed_web, list) else getattr(heuristic, "directed_web_queries", []),
                critique_summary=ai_summary,
                input_tokens=c_in,
                output_tokens=c_out,
            )
        except Exception:
            return heuristic
